

// startsWith(searchString, index number) -> check a string starts with another string

const message1 = "Today is friday";
console.log(message1.startsWith('Today', 0)) // if we use today it will show false

// endsWith (searchString, length) -> check a string ends with another string

const message2 = "Today is friday";
console.log(message2.endsWith('friday'))

// includes(searchString, index number) -> check if a string contains another string

const message3 = "Today is friday";
console.log(message3.includes('friday')) // checking if the string has the friday word

// all these methods are case sensitive




