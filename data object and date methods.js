
var date = new Date();
document.write(date + "<br>");

var year = date.getFullYear();
document.write(year + "<br>");

var month = date.getMonth();
document.write(month + "<br>");// its index number starts with 0, like January = 0, February = 1, and so on

var currentDate = date.getDate();
document.write(currentDate + "<br>");

var currentDay = date.getDay();
document.write(currentDay + "<br>"); // its index starts with 0, like Sunday = 0, Monday = 1,and so on

var currentHour = date.getHours();
document.write(currentHour + "<br>");

var currentMinutes = date.getMinutes();
document.write(currentMinutes + "<br>");

